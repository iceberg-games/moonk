export const ITEMS_BY_ID = Object.fromEntries(ITEMS.map((item) => [item.id, item]));

export function itemsForSlot(slot) {
  return ITEMS.filter((item) => item.slot === slot);
}

export function serializeItem(item, tris) {
  return {
    id: item.id,
    name: item.name,
    slot: item.slot,
    attach: item.attach,
    rarity: item.rarity,
    price: item.price,
    currency: item.price == null ? null : CURRENCY.id,
    unlock: item.unlock,
    unlockLabel: item.unlockLabel,
    description: item.description,
    special: item.special ?? null,
    tris: tris ?? item.tris ?? 0,
  };
}
